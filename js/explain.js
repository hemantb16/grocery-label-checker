// Glossary entries whose German word appears in the ingredient text, in reading order.
export function germanTerms(text) {
  const lower = (text || '').toLowerCase();
  const found = [];
  for (const [de, en, note] of GLOSSARY) {
    const i = lower.indexOf(de);
    // Skip a word that is only part of a longer glossary word already found ("aroma" inside "natürliches aroma").
    if (i !== -1 && !found.some((f) => f.de.includes(de) && lower.indexOf(f.de) <= i && i < lower.indexOf(f.de) + f.de.length)) {
      found.push({ de, en, note, i, word: text.slice(i, i + de.length) });
    }
  }
  return found.sort((a, b) => a.i - b.i);
}
