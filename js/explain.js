// "e322i" -> look up "e322" when there is no specific entry.
export function explainAdditive(tag) {
  const code = tag.toLowerCase();
  const hit = ADDITIVES[code] || ADDITIVES[code.replace(/[a-z]+$/, '').replace(/^(e\d+)[a-z]*$/, '$1')];
  return hit ? { code, name: hit[0], note: hit[1], animal: hit[2] === 'animal' } : { code, name: null, note: null, animal: false };
}

